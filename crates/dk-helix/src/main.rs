//! dk-helix — HelixDB container for the dkod-engine code-intelligence knowledge graph.
//!
//! This binary embeds a HelixDB instance that stores repo/file/symbol/commit
//! nodes and the edges between them (Defines, Calls, Imports, …).
//!
//! Run with:
//!   HELIX_PORT=6969 HELIX_DATA_DIR=/tmp/helix cargo run -p dk-helix
//!
//! The MCP endpoint is exposed on the same port, so any MCP client pointed at
//! `http://localhost:6969/mcp` can introspect and traverse the knowledge graph.

use helix_db::helix_engine::{
    storage_core::version_info::{ItemInfo, Transition, TransitionFn, TransitionSubmission, VersionInfo},
    traversal_core::{HelixGraphEngine, HelixGraphEngineOpts},
};
use helix_db::helix_gateway::mcp::mcp::{MCPHandlerFn, MCPHandlerSubmission};
use helix_db::helix_gateway::{
    gateway::{GatewayOpts, HelixGateway},
    router::router::{HandlerFn, HandlerSubmission},
};
use std::{collections::HashMap, sync::Arc};
use tracing::info;
use tracing_subscriber::{layer::SubscriberExt, util::SubscriberInitExt, Layer};

mod queries;

fn main() {
    let env_res = dotenvy::dotenv();

    tracing_subscriber::registry()
        .with(
            tracing_subscriber::fmt::layer().with_filter(tracing_subscriber::filter::filter_fn(
                |metadata| {
                    let target = metadata.target();
                    !target.starts_with("axum")
                        && !target.starts_with("hyper")
                        && !target.starts_with("tower")
                        && !target.starts_with("h2")
                        && !target.starts_with("reqwest")
                },
            )),
        )
        .init();

    match env_res {
        Ok(_) => info!("Loaded .env file"),
        Err(e) => info!(?e, "Didn't load .env file"),
    }

    let config = queries::config().unwrap_or_default();

    let path = match std::env::var("HELIX_DATA_DIR") {
        Ok(val) => std::path::PathBuf::from(val).join("dk-helix"),
        Err(_) => {
            let home = dirs::home_dir().expect("Could not retrieve home directory");
            home.join(".helix/dk-helix")
        }
    };

    let port = std::env::var("HELIX_PORT")
        .ok()
        .and_then(|v| v.parse::<u16>().ok())
        .unwrap_or(6969);

    info!("dk-helix starting on port {port}, data at {}", path.display());

    // Collect schema migration transitions (empty for v1)
    let transition_fns: HashMap<&'static str, ItemInfo> =
        inventory::iter::<TransitionSubmission>
            .into_iter()
            .fold(HashMap::new(), |mut acc, TransitionSubmission(Transition { item_label, func, from_version, to_version })| {
                acc.entry(item_label)
                    .and_modify(|info: &mut ItemInfo| {
                        info.latest = info.latest.max(*to_version);
                        info.transition_fns.push(TransitionFn {
                            from_version: *from_version,
                            to_version: *to_version,
                            func: *func,
                        });
                        info.transition_fns.sort_by_key(|f| f.from_version);
                    });
                acc
            });

    let opts = HelixGraphEngineOpts {
        path: path.to_str().expect("non-UTF-8 path").to_string(),
        config,
        version_info: VersionInfo(transition_fns),
    };

    let graph = Arc::new(
        HelixGraphEngine::new(opts.clone())
            .unwrap_or_else(|e| panic!("Failed to create HelixGraphEngine: {e}")),
    );

    // HTTP route submissions (generated by #[handler] in queries.rs)
    let (query_routes, write_routes): (HashMap<String, HandlerFn>, std::collections::HashSet<String>) =
        inventory::iter::<HandlerSubmission>
            .into_iter()
            .fold((HashMap::new(), std::collections::HashSet::new()), |(mut routes, mut writes), sub| {
                let h = &sub.0;
                routes.insert(h.name.to_string(), Arc::new(h.func));
                if h.is_write {
                    writes.insert(h.name.to_string());
                }
                (routes, writes)
            });

    // MCP route submissions (generated by #[mcp_handler] in queries.rs)
    let mcp_routes: HashMap<String, MCPHandlerFn> =
        inventory::iter::<MCPHandlerSubmission>
            .into_iter()
            .map(|sub| {
                let h = &sub.0;
                (h.name.to_string(), Arc::new(h.func) as MCPHandlerFn)
            })
            .collect();

    info!("HTTP routes: {:?}", query_routes.keys().collect::<Vec<_>>());
    info!("MCP tools:   {:?}", mcp_routes.keys().collect::<Vec<_>>());

    HelixGateway::new(
        &format!("0.0.0.0:{port}"),
        graph,
        GatewayOpts::DEFAULT_WORKERS_PER_CORE,
        Some(query_routes),
        Some(mcp_routes),
        Some(write_routes),
        Some(opts),
    )
    .run()
    .expect("HelixGateway failed");
}
